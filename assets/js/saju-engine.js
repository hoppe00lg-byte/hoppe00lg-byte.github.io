    /* 년주 — 입춘 경계 */
    var licun = yearTerms(y)[1];
    var pillarYear = moment >= licun.key ? y : y - 1;
    var yearIdx = ((pillarYear - 4) % 60 + 60) % 60;
    var yearStem = yearIdx % 10, yearBranch = yearIdx % 12;

    /* 월주 — 절기(節) 경계 */
    var boundaries = [];
    [y - 1, y, y + 1].forEach(function (yy) {
      var terms = yearTerms(yy);
      if (terms) boundaries = boundaries.concat(terms);
    });
    boundaries.sort(function (a, b) { return a.key - b.key; });
    var current = null, prev = null, next = null;
    for (var i = 0; i < boundaries.length; i++) {
      if (boundaries[i].key <= moment) { current = boundaries[i]; }
      else if (boundaries[i].key > moment) { next = boundaries[i]; break; }
    }
    // current 는 반드시 존재(표 범위 안). 방어적으로 처리.
    if (!current) return { ok: false, error: '절기 경계를 찾지 못했습니다.' };
    for (var j = 0; j < boundaries.length; j++) {
      if (boundaries[j].key < current.key) prev = boundaries[j];
    }
