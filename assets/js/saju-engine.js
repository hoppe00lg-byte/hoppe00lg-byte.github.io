    if (!(m >= 1 && m <= 12)) return { ok: false, error: '태어난 달을 선택해 주세요.' };
    if (!(d >= 1 && d <= daysInMonth(y, m))) return { ok: false, error: '태어난 날짜를 확인해 주세요.' };
    if (hour !== null && !(hour >= 0 && hour <= 23)) return { ok: false, error: '태어난 시각을 확인해 주세요.' };
    if (!JIEQI[y]) return { ok: false, error: '이 연도의 절기 데이터가 없습니다.' };

